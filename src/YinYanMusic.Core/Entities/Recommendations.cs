namespace YinYanMusic.Core.Entities;

/// <summary>
/// 后台人工干预推荐位（V2.12）。一行 = 对某个歌单的一次人工干预；**没有行 = 该歌单完全交给规则排序**。
///
/// <para>为什么是"独立表 + 左连接"而不是往 <see cref="Playlist"/> 上加三个列：
/// 绝大多数歌单永远不会有干预（运营只调头部十几个），加列会让 99% 的行存三个恒为 0 的死字段，
/// 而且"没干预"和"干预为 0"这两种状态在列上没法区分。独立表让"有没有干预"就是"有没有行"。</para>
///
/// <para>主键就是 PlaylistId（不是自增 Id）：一个歌单只允许一条干预记录，
/// 用主键而不是唯一索引来保证 —— 后台重复提交时是 UPDATE 而不是插出第二行。</para>
/// </summary>
public class AdminRecommended
{
    public long PlaylistId { get; set; }
    public Playlist Playlist { get; set; } = default!;

    /// <summary>
    /// 人工置顶序号：0 = 不置顶；&gt;= 1 = 置顶，数字小的排在前面。
    /// 置顶的排在**所有未置顶的歌单之前**，即人工序优先于规则分（TC-2.12-07）。
    /// 之所以用"0 表示不置顶"而不是可空列：后台表单里 0 就是"没置顶"这一句人话，
    /// 不存在"空值 vs 0"的歧义，前端也不用额外处理 null。
    /// </summary>
    public int SortOrder { get; set; }

    /// <summary>
    /// 加权分：**加到场景规则分上**，只影响名次不改规则本身。
    /// 例：运营想让某新歌单在"热播"里往前挪，但不想把它设成置顶，就给 500 分。
    /// 可以是负数（压低某个高播放量但内容不好的歌单）。
    /// </summary>
    public int Weight { get; set; }

    /// <summary>
    /// 下线：true 时该歌单从**全部推荐场景**里消失（不是只从某一个场景）。
    /// 为什么不做成"按场景下线"：运营的原话就是"这个歌单先别推荐了"，
    /// 按场景拆会让后台表单变成 4 个复选框；真需要按场景区分时再加场景列，现在不做。
    /// 注意：下线只影响推荐位，歌单本身照常在搜索/分区/歌单详情里可见可听。
    /// </summary>
    public bool IsHidden { get; set; }
}
